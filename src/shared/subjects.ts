/** 一覧に無い科目のための、最小限のツリー。あとで Claude に調整させる前提。 */
const GENERIC_OUTLINE = `
基礎知識: 用語と基本事項, 基本的な計算・処理
標準問題: 典型問題の解法, 資料・条件の読み取り
応用問題: 複数分野の融合, 記述・論述`;

/** 「親: 子, 子」の並びを単元ツリーにする。ID は位置から決める(u01、u01-02)。 */
export function parseOutline(outline: string): UnitNode[] {
  const pad = (n: number) => String(n).padStart(2, '0');
  return outline
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((line, i) => {
      const idx = line.indexOf(':');
      const parent = (idx >= 0 ? line.slice(0, idx) : line).trim();
      const kids = idx >= 0 ? splitTopLevel(line.slice(idx + 1)) : [];
      const id = `u${pad(i + 1)}`;
      return {
        id,
        name: parent,
        weight: 1,
        children: kids.map((k, j) => ({ id: `${id}-${pad(j + 1)}`, name: k, weight: 1, children: [] })),
      };
    });
}

/** かっこの中の「,」「・」では切らずに、「, 」で区切る。 */
function splitTopLevel(text: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let cur = '';
  for (const ch of text) {
    if (ch === '(' || ch === '(') depth++;
    if (ch === ')' || ch === ')') depth = Math.max(0, depth - 1);
    if (ch === ',' && depth === 0) {
      if (cur.trim()) out.push(cur.trim());
      cur = '';
    } else {
      cur += ch;
    }
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

export function presetFor(subjectName: string): SubjectPreset | null {
  return SUBJECT_PRESETS.find((p) => p.name === subjectName) ?? null;
}

/** 科目名から初期の単元ツリーを作る。 */
export function initialUnitTree(subjectName: string): UnitNode[] {
  return parseOutline(presetFor(subjectName)?.outline ?? GENERIC_OUTLINE);
}

/** ツリーを平らにする(葉だけでなく全ノード)。 */
export function flattenUnits(tree: UnitNode[], parentName = ''): Array<{ id: string; name: string; fullName: string; weight: number; leaf: boolean; depth: number }> {
  const out: Array<{ id: string; name: string; fullName: string; weight: number; leaf: boolean; depth: number }> = [];
  const walk = (nodes: UnitNode[], prefix: string, depth: number, inherited: number) => {
    for (const n of nodes) {
      const fullName = prefix ? `${prefix} > ${n.name}` : n.name;
      const weight = inherited === 0 ? 0 : n.weight;
      out.push({ id: n.id, name: n.name, fullName, weight, leaf: n.children.length === 0, depth });
      walk(n.children, fullName, depth + 1, weight);
    }
  };
  walk(tree, parentName, 0, 1);
  return out;
}

/** 出題の対象になる単元(葉で、重みが 0 でないもの)。 */
export function leafUnits(tree: UnitNode[]) {
  return flattenUnits(tree).filter((u) => u.leaf && u.weight > 0);
}

export function findUnit(tree: UnitNode[], id: string): UnitNode | null {
  for (const n of tree) {
    if (n.id === id) return n;
    const hit = findUnit(n.children, id);
    if (hit) return hit;
  }
  return null;
}
